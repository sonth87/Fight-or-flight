/** Decode the RLE-compressed base64 voxel data into 13 slices of 34x46 (1564 bytes each). */
export function decodeJetSlices(): Uint8Array[] {
  const binary = atob(JET_VOXEL_RLE_BASE64);
  const buffer = new Uint8Array(1564 * 13);
  let offset = 0;
  for (let i = 0; i < binary.length; i += 2) {
    const count = binary.charCodeAt(i);
    const val = binary.charCodeAt(i + 1);
    buffer.fill(val, offset, offset + count);
    offset += count;
  }
  const slices: Uint8Array[] = [];
  for (let s = 0; s < 13; s++) {
    slices.push(buffer.subarray(s * 34 * 46, (s + 1) * 34 * 46));
  }
  return slices;
}

