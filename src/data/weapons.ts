export const GATE_BASE_COLORS: Record<WeaponKind, RgbTuple> = {
  gun: [255, 96, 40],
  missile: [32, 170, 255],
  shield: [168, 72, 255],
  craft: [255, 200, 32],
};

export function rgbToCss(rgb: RgbTuple | number[]): string {
  return `rgb(${rgb[0] | 0},${rgb[1] | 0},${rgb[2] | 0})`;
}

export function getGateColors(weaponOrId: string | SpecialWeaponDef): GateColorScheme {
  const def = typeof weaponOrId === 'string' ? SPECIAL_WEAPONS[weaponOrId] : weaponOrId;
  const kind: WeaponKind = (def && def.kind) || 'gun';
  const base = GATE_BASE_COLORS[kind] || GATE_BASE_COLORS.gun;
  const variant = (def && def.color) || base;
  return {
    base,
    variant,
    kind,
    cssBase: rgbToCss(base),
    cssVariant: rgbToCss(variant),
  };
}
